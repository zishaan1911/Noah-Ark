"""Generate TypeScript, Python (Pydantic v2) and Dart types from shared/schemas into shared/generated.

Run from anywhere: python shared/scripts/codegen.py
Needs: node/npx (json-schema-to-typescript, quicktype) and datamodel-code-generator (requirements.txt).
"""

import json
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SCHEMAS = ROOT / "schemas"
OUT = ROOT / "generated"
JSON2TS = "json-schema-to-typescript@15.0.4"
QUICKTYPE = "quicktype@25.1.0"
NPX = shutil.which("npx") or "npx"

# Every type a consumer needs, so each is emitted once from one root.
ENTRIES = {
    "sosRequest": "sos-request.schema.json",
    "sosReport": "sos-request.schema.json#/$defs/report",
    "sosTriage": "sos-request.schema.json#/$defs/triage",
    "mission": "mission.schema.json",
    "missionRequest": "mission.schema.json#/$defs/request",
    "telemetry": "telemetry.schema.json",
    "droneCommand": "drone-command.schema.json",
    "droneEvent": "drone-event.schema.json",
    "drone": "drone.schema.json",
    "liveUpdate": "live-update.schema.json",
    "manualControl": "manual-control.schema.json",
    "weather": "weather.schema.json",
}
# Ark SOS only sends and reads SOS requests; quicktype cannot express the LiveUpdate union in Dart anyway.
DART_ENTRIES = ("sosRequest", "sosReport", "sosTriage")
HEADER = "Generated by shared/scripts/codegen.py from shared/schemas. Do not edit."


def run(*cmd: str) -> None:
    subprocess.run(cmd, check=True)


def shape_only(node):
    """Drop validation-only combinators (if/then/else, allOf/anyOf next to `properties`).

    They add rules, not fields, and json-schema-to-typescript turns such objects into `{[k: string]: unknown}`.
    Validation still uses the full schemas; generated types only carry the shape.
    """
    if isinstance(node, list):
        return [shape_only(v) for v in node]
    if not isinstance(node, dict):
        return node
    drop = {"if", "then", "else"} | ({"allOf", "anyOf"} if "properties" in node else set())
    return {k: shape_only(v) for k, v in node.items() if k not in drop}


def main() -> None:
    def root(names) -> str:
        return json.dumps(
            {
                "$schema": "https://json-schema.org/draft/2020-12/schema",
                "title": "Contracts",
                "description": "Codegen root only; not a message.",
                "type": "object",
                "additionalProperties": False,
                "properties": {k: {"$ref": ENTRIES[k]} for k in names},
            }
        )

    for d in ("typescript", "python", "dart"):
        (OUT / d).mkdir(parents=True, exist_ok=True)

    with tempfile.TemporaryDirectory() as tmp:
        # The root sits next to the schemas so relative $refs resolve for every tool.
        work = Path(tmp) / "schemas"
        work.mkdir()
        for src in SCHEMAS.glob("*.schema.json"):
            (work / src.name).write_text(json.dumps(shape_only(json.loads(src.read_text("utf-8")))), "utf-8")
        (work / "_root.json").write_text(root(ENTRIES), encoding="utf-8")
        (work / "_dart.json").write_text(root(DART_ENTRIES), encoding="utf-8")

        ts = OUT / "typescript" / "contracts.ts"
        run(
            NPX, "-y", JSON2TS, "-i", str(work / "_root.json"), "-o", str(ts), "--cwd", str(work), "--bannerComment", ""
        )
        ts.write_text(f"/* eslint-disable */\n// {HEADER}\n\n" + ts.read_text("utf-8"), "utf-8")

        py = OUT / "python" / "ark_contracts"  # a package: the schemas reference each other
        shutil.rmtree(py, ignore_errors=True)
        run(
            sys.executable,
            "-m",
            "datamodel_code_generator",
            "--input",
            str(work / "_root.json"),
            "--input-file-type",
            "jsonschema",
            "--output",
            str(py),
            "--output-model-type",
            "pydantic_v2.BaseModel",
            "--target-python-version",
            "3.12",
            "--use-title-as-name",
            "--use-double-quotes",
            "--disable-timestamp",
            "--custom-file-header",
            f"# {HEADER}",
        )

        dart = OUT / "dart" / "contracts.dart"
        run(
            NPX,
            "-y",
            QUICKTYPE,
            "--lang",
            "dart",
            "--src-lang",
            "schema",
            "--top-level",
            "Contracts",
            "--null-safety",
            "--required-props",
            "-o",
            str(dart),
            str(work / "_dart.json"),
        )
        dart.write_text(f"// {HEADER}\n" + dart.read_text("utf-8"), "utf-8")
    print(f"wrote {ts}, {py}, {dart}")


if __name__ == "__main__":
    main()
